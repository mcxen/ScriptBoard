var (
	svgMu    sync.Mutex
	svgCache = map[string]*ui.SVG{}
)

// ParseSVG parses and caches an inline SVG string for .bar Icon nodes.
func ParseSVG(raw string) *ui.SVG {
	if raw == "" {
		return nil
	}
	svgMu.Lock()
	if s, ok := svgCache[raw]; ok {
		svgMu.Unlock()
		return s
	}
	svgMu.Unlock()

	s, err := ui.ParseSVG([]byte(raw))
	if err != nil {
		return nil
	}
	svgMu.Lock()
	if len(svgCache) > 256 {
		svgCache = map[string]*ui.SVG{}
	}
	svgCache[raw] = s
	svgMu.Unlock()
	return s
}

// DefaultIcon resolves common Lucide-style icon names for standalone/headless
// rendering when the host app does not supply an icon resolver.
func DefaultIcon(name string) *ui.SVG {
	key := strings.TrimSpace(strings.TrimPrefix(name, "lucide:"))
	key = strings.ReplaceAll(key, ".", "-")
	if key == "" {
		return nil
	}
	if inner, ok := builtinIconPaths[key]; ok {
		return ParseSVG(`<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 24 24" fill="none" stroke="currentColor" stroke-width="2" stroke-linecap="round" stroke-linejoin="round">` + inner + `</svg>`)
	}
	return nil
}

